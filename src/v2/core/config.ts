import { lstat, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { KF_VERSION } from '../version';
import { KnowleryError } from './errors';
import { validateIgnore } from './ignore';
import { isMissing, resolveInside, WIKI_DIR } from './paths';

const BETA1_WIKI_DIR = 'wiki';
const GENERATED_CONVENTIONS_PREFIX = '<!-- Generated by knowlery for kf ';

export class Beta1WikiError extends KnowleryError {
  constructor(message: string, recovery: string) {
    super('unsupported_schema', message, recovery);
    this.name = 'Beta1WikiError';
  }
}

export async function checkBeta1Wiki(root: string): Promise<void> {
  const legacyConventionsPath = join(root, BETA1_WIKI_DIR, 'CONVENTIONS.md');
  let text: string;
  try {
    const info = await lstat(legacyConventionsPath);
    if (!info.isFile()) return;
    text = await readFile(legacyConventionsPath, 'utf8');
  } catch (error) {
    if (isMissing(error)) return;
    throw error;
  }

  const firstLine = text.replace(/\r\n/g, '\n').split('\n')[0] ?? '';
  if (!firstLine.startsWith(GENERATED_CONVENTIONS_PREFIX)) return;

  let hiddenWikiExists = false;
  try {
    await lstat(join(root, WIKI_DIR));
    hiddenWikiExists = true;
  } catch (error) {
    if (!isMissing(error)) throw error;
  }

  const recovery = hiddenWikiExists
    ? `Both ${BETA1_WIKI_DIR}/ and ${WIKI_DIR}/ exist. Knowlery does not choose. Merge the pages into ${WIKI_DIR}/ by hand, then remove ${BETA1_WIKI_DIR}/.`
    : `In the knowledge base folder run: mv ${BETA1_WIKI_DIR} ${WIKI_DIR}   Then run: knowlery sync --apply`;

  throw new Beta1WikiError(
    `Found ${BETA1_WIKI_DIR}/ made by an earlier 2.0 beta. The wiki now lives in ${WIKI_DIR}/.`,
    recovery,
  );
}

export interface Config {
  kf: string;
  ignore: string[];
  mcp: { raw: boolean };
}

export function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export async function readConfig(root: string): Promise<Config> {
  await checkBeta1Wiki(root);
  let text: string;
  try {
    text = await readFile(await resolveInside(root, '.knowlery/config.json'), 'utf8');
  } catch (error) {
    if (isMissing(error)) {
      throw new KnowleryError('not_found', 'This is not a knowledge base: .knowlery/config.json is missing.', 'Create .knowlery/config.json containing {"kf":"2.0"}.');
    }
    throw error;
  }
  const invalid = () => new KnowleryError('invalid_config', 'Invalid .knowlery/config.json.', 'Provide a JSON object with string kf, optional string[] ignore and optional boolean mcp.raw.');
  let value: unknown;
  try {
    value = JSON.parse(text) as unknown;
  } catch {
    throw invalid();
  }
  if (!isObject(value) || typeof value.kf !== 'string') throw invalid();
  if (value.kf !== KF_VERSION) {
    throw new KnowleryError('unsupported_schema', `Unsupported knowledge format: ${value.kf}`, 'Use a knowledge base with kf "2.0".');
  }
  const ignore = value.ignore ?? [];
  if (value.ignore === null || !Array.isArray(ignore) || !ignore.every((entry): entry is string => typeof entry === 'string')) throw invalid();
  for (const entry of ignore) validateIgnore(entry);
  if (value.mcp !== undefined && !isObject(value.mcp)) throw invalid();
  const raw = isObject(value.mcp) ? value.mcp.raw : undefined;
  if (raw !== undefined && typeof raw !== 'boolean') throw invalid();
  return { kf: value.kf, ignore, mcp: { raw: raw ?? true } };
}
