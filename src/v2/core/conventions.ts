function codeList(items: readonly string[]): string {
  return items.map((item) => `\`${item}\``).join(', ');
}

function mapBullets(entries: Record<string, string>): string[] {
  return Object.entries(entries).map(([key, meaning]) => `- \`${key}\`: ${meaning}`);
}

