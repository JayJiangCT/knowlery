import type { PageType } from '../schema/kf-2.0';
import type { ParsedPage } from './page/model';

const GROUP_ORDER: readonly (PageType | 'other')[] = [
  'synthesis',
  'concept',
  'entity',
  'comparison',
  'source',
  'other',
];

const VALID_TYPES = new Set<string>(['synthesis', 'concept', 'entity', 'comparison', 'source']);

function sanitizeValue(value: string): string {
  return value.replace(/\r?\n/g, ' ').trim();
}

function escapeTitle(title: string): string {
  return sanitizeValue(title).replace(/[[\]]/g, (ch) => `\\${ch}`);
}

function compareStrings(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

export function renderWikiIndex(pages: ParsedPage[]): string {
  const groups = new Map<PageType | 'other', ParsedPage[]>();
  for (const group of GROUP_ORDER) groups.set(group, []);

  for (const page of pages) {
    const type = page.frontmatter.type;
    const key: PageType | 'other' = type && VALID_TYPES.has(type) ? type : 'other';
    groups.get(key)!.push(page);
  }

  const sections: string[] = [
    '# Index',
    '',
    'Generated by `knowlery index rebuild` from page frontmatter. Do not edit: it is overwritten.',
  ];

  for (const group of GROUP_ORDER) {
    const entries = groups.get(group)!;
    if (entries.length === 0) continue;

    entries.sort((a, b) => {
      const titleA = sanitizeValue(a.frontmatter.title ?? a.slug).toLowerCase();
      const titleB = sanitizeValue(b.frontmatter.title ?? b.slug).toLowerCase();
      return compareStrings(titleA, titleB) || compareStrings(a.slug, b.slug);
    });

    sections.push('', `## ${group}`, '');
    for (const page of entries) {
      const rawTitle = page.frontmatter.title ? sanitizeValue(page.frontmatter.title) : '';
      const displayTitle = rawTitle ? escapeTitle(rawTitle) : escapeTitle(page.slug);
      const parts = [`- [${displayTitle}](${page.slug}.md)`];
      const status = page.frontmatter.status ? sanitizeValue(page.frontmatter.status) : '';
      if (status) parts.push(status);
      const description = page.frontmatter.description ? sanitizeValue(page.frontmatter.description) : '';
      if (description) parts.push(description);
      sections.push(parts.join(' · '));
    }
  }

  return `${sections.join('\n')}\n`;
}
