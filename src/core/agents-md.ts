import matter from 'gray-matter';
import type { VaultFs } from './vault-fs';
import { normalizeVaultPath } from './vault-fs';

export const AGENTS_MD_PATH = 'AGENTS.md';
/**
 * The one rules directory, for every platform. `.agents/` is the vendor-neutral
 * home the skills already use (`.agents/skills/` is the Codex convention and
 * Knowlery's canonical skills dir); there is no cross-vendor "rules" standard,
 * so the rules are delivered by inlining them into AGENTS.md rather than by a
 * per-platform directory.
 */
export const RULES_DIR = '.agents/rules';
export const AGENTS_MD_MANAGED_START = '<!-- Knowlery managed:start -->';
export const AGENTS_MD_MANAGED_END = '<!-- Knowlery managed:end -->';

export interface AgentsMdRule {
  /** Path relative to the rules directory, e.g. `citation-required.md`. */
  path: string;
  content: string;
}

export interface AgentsMdSource {
  knowledgeMd: string;
  rules: AgentsMdRule[];
}

/**
 * AGENTS.md (agents.md, Agentic AI Foundation) is the cross-vendor instruction
 * file: Codex, OpenCode, Cursor, Gemini CLI and others read it natively, and
 * Claude Code's documented pattern is a CLAUDE.md that `@`-imports it. None of
 * the native readers support imports, so the fixed context — the operating card
 * plus the rules — is inlined here and this file is the single source every
 * platform ends up with. The block is regenerated from KNOWLEDGE.md and
 * `.agents/rules/*.md` on sync; user prose outside the markers is preserved.
 *
 * Size note: Codex caps the whole project-instruction chain at 32 KiB by default
 * (`project_doc_max_bytes`). The default card plus the four bundled rules is
 * roughly 9 KB, leaving headroom for user rules.
 */
export function renderAgentsMdBlock(source: AgentsMdSource): string {
  const sections = [
    source.knowledgeMd.trim(),
    ...source.rules.map((rule) => renderRuleBody(rule.content)),
  ].filter((section) => section.length > 0);

  return [
    AGENTS_MD_MANAGED_START,
    `<!-- Generated by Knowlery from KNOWLEDGE.md and ${RULES_DIR}/*.md. Codex and OpenCode read this file directly; Claude Code loads it through .claude/CLAUDE.md. Edit those source files, not this block; it is rewritten on sync. Text outside the markers is yours and is kept. -->`,
    '',
    sections.join('\n\n'),
    '',
    AGENTS_MD_MANAGED_END,
  ].join('\n');
}

/**
 * Claude Code scopes a rule to files via `paths:` frontmatter. Other platforms
 * have no such mechanism, so inlining the YAML verbatim would leave a bare `---`
 * block mid-document; the scope is restated as a sentence under the heading instead.
 */
export function renderRuleBody(content: string): string {
  let parsed: ReturnType<typeof matter>;
  try {
    parsed = matter(content);
  } catch {
    return content.trim();
  }

  const body = parsed.content.trim();
  const paths = Array.isArray(parsed.data.paths)
    ? (parsed.data.paths as unknown[]).filter((path): path is string => typeof path === 'string')
    : typeof parsed.data.paths === 'string'
      ? parsed.data.paths.split(',').map((path) => path.trim()).filter((path) => path.length > 0)
      : [];
  if (paths.length === 0) return body;

  const scope = `_Applies to files matching: ${paths.map((path) => `\`${path}\``).join(', ')}_`;
  const [firstLine, ...rest] = body.split('\n');
  return firstLine.startsWith('#')
    ? [firstLine, '', scope, ...rest].join('\n')
    : [scope, '', body].join('\n');
}

/**
 * With markers present the block is replaced in place. Without markers (a
 * pre-existing, hand-written AGENTS.md) the block goes *first* and the user's
 * text follows — the same order Claude Code documents for CLAUDE.md ("loads the
 * imported file, then appends the rest"): shared instructions lead, additions
 * trail. Nothing of the user's is dropped; `resetAgentsMd` is the explicit way
 * to discard it.
 */
export function mergeAgentsMd(existing: string | null, block: string): string {
  if (existing === null || existing.trim().length === 0) {
    return `${block}\n`;
  }

  const start = existing.indexOf(AGENTS_MD_MANAGED_START);
  const end = existing.indexOf(AGENTS_MD_MANAGED_END, start + AGENTS_MD_MANAGED_START.length);
  if (start !== -1 && end !== -1) {
    const before = existing.slice(0, start);
    const after = existing.slice(end + AGENTS_MD_MANAGED_END.length);
    return `${before}${block}${after.endsWith('\n') ? after : `${after}\n`}`;
  }

  return `${block}\n\n${existing.trim()}\n`;
}

/** Every `.md` under `dir`, recursively, as sorted paths relative to `dir`. */
export async function collectRulePaths(fs: VaultFs, dir: string = RULES_DIR): Promise<string[]> {
  const root = normalizeVaultPath(dir);
  if (!(await fs.exists(root))) return [];

  const found: string[] = [];
  async function walk(current: string): Promise<void> {
    const listing = await fs.list(normalizeVaultPath(current));
    for (const filePath of listing.files) {
      const normalized = normalizeVaultPath(filePath);
      if (!normalized.endsWith('.md')) continue;
      if (!normalized.startsWith(`${root}/`)) continue;
      found.push(normalized.slice(root.length + 1));
    }
    for (const folderPath of listing.folders) {
      await walk(folderPath);
    }
  }
  await walk(root);

  return [...new Set(found)].sort((a, b) => a.localeCompare(b));
}

export async function readAgentsMdSource(fs: VaultFs): Promise<AgentsMdSource | null> {
  if (!(await fs.exists('KNOWLEDGE.md'))) return null;
  const knowledgeMd = await fs.read('KNOWLEDGE.md');

  const rules: AgentsMdRule[] = [];
  for (const path of await collectRulePaths(fs)) {
    rules.push({ path, content: await fs.read(`${RULES_DIR}/${path}`) });
  }

  return { knowledgeMd, rules };
}

/**
 * Write-on-change: an unconditional write would churn the file's mtime on every
 * plugin load. Skips silently when KNOWLEDGE.md is absent (vault not initialized).
 */
export async function syncAgentsMd(fs: VaultFs): Promise<void> {
  const source = await readAgentsMdSource(fs);
  if (!source) return;

  const fileExists = await fs.exists(AGENTS_MD_PATH);
  const existing = fileExists ? await fs.read(AGENTS_MD_PATH) : null;
  const merged = mergeAgentsMd(existing, renderAgentsMdBlock(source));
  if (!fileExists || merged !== existing) {
    await fs.write(AGENTS_MD_PATH, merged);
  }
}

/**
 * The explicit, user-initiated cleanup: rewrites AGENTS.md as the managed block
 * alone, discarding everything outside the markers (typically the pre-Knowlery
 * instructions a vault carried). Sync never does this on its own.
 */
export async function resetAgentsMd(fs: VaultFs): Promise<void> {
  const source = await readAgentsMdSource(fs);
  if (!source) return;
  await fs.write(AGENTS_MD_PATH, mergeAgentsMd(null, renderAgentsMdBlock(source)));
}
