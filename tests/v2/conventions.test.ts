import { describe, expect, it } from 'vitest';
import { renderConventions } from '../../src/v2/core/conventions';
import { parsePage } from '../../src/v2/core/page/parse';
import { KF_SCHEMA } from '../../src/v2/schema/kf-2.0';

describe('v2 conventions', () => {
  it('renders deterministically under 12,288 bytes and covers every KF_SCHEMA symbol', () => {
    const first = renderConventions();
    const second = renderConventions();

    expect(first).toBe(second);
    expect(Buffer.byteLength(first, 'utf8')).toBeLessThan(12288);
    expect(first.startsWith(
      `<!-- Generated by knowlery for kf ${KF_SCHEMA.kf}. Do not edit: knowlery sync --apply overwrites this file. -->`,
    )).toBe(true);

    for (const type of Object.keys(KF_SCHEMA.page_types)) {
      expect(first).toContain(`\`${type}\``);
    }
    for (const status of KF_SCHEMA.statuses) {
      expect(first).toContain(`\`${status}\``);
    }
    for (const relation of Object.keys(KF_SCHEMA.relations)) {
      expect(first).toContain(`\`${relation}\``);
    }
    for (const section of KF_SCHEMA.sections) {
      expect(first).toContain(`## ${section}`);
    }
    for (const specialFile of KF_SCHEMA.special_files) {
      expect(first).toContain(`\`${specialFile}\``);
    }
    for (const event of KF_SCHEMA.history_events) {
      expect(first).toContain(`\`${event}\``);
    }
    for (const code of KF_SCHEMA.rule_codes) {
      expect(first).toContain(`\`${code}\``);
    }
    for (const format of KF_SCHEMA.quote_required_formats) {
      expect(first).toContain(`\`${format}\``);
    }
    expect(first).toContain(String(KF_SCHEMA.quote_max_chars));
  });

  it('embeds an example page that parses with zero problems as delivery-limit.md', () => {
    const text = renderConventions();
    const match = /```markdown\n([\s\S]*?)\n```/.exec(text);
    expect(match).not.toBeNull();
    const parsed = parsePage(`${match![1]}\n`, 'delivery-limit.md');
    expect(parsed.problems).toEqual([]);
  });
});
